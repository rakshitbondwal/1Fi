/**
 * Calculates dynamic EMI plans for any given variant price.
 * 1Fi specializes in 0% interest No-Cost EMIs backed by Mutual Funds.
 */
export function generateEmiPlans(priceInPaise: number): EMIPlan[] {
  return [
    {
      id: "emi_3m",
      tenureMonths: 3,
      monthlyInstallmentInPaise: Math.round(priceInPaise / 3),
      interestRatePct: 0,
      totalPayableInPaise: priceInPaise,
      isNoCost: true,
      savingsVsCreditCardInPaise: Math.round(priceInPaise * 0.04),
    },
    {
      id: "emi_6m",
      tenureMonths: 6,
      monthlyInstallmentInPaise: Math.round(priceInPaise / 6),
      interestRatePct: 0,
      totalPayableInPaise: priceInPaise,
      isNoCost: true,
      savingsVsCreditCardInPaise: Math.round(priceInPaise * 0.08),
    },
    {
      id: "emi_9m",
      tenureMonths: 9,
      monthlyInstallmentInPaise: Math.round((priceInPaise * 1.03) / 9),
      interestRatePct: 3,
      totalPayableInPaise: Math.round(priceInPaise * 1.03),
      isNoCost: false,
      savingsVsCreditCardInPaise: Math.round(priceInPaise * 0.09),
    },
    {
      id: "emi_12m",
      tenureMonths: 12,
      monthlyInstallmentInPaise: Math.round((priceInPaise * 1.05) / 12),
      interestRatePct: 5,
      totalPayableInPaise: Math.round(priceInPaise * 1.05),
      isNoCost: false,
      savingsVsCreditCardInPaise: Math.round(priceInPaise * 0.11),
    },
  ];
}

